function toolBlock(){
  return AGENT_TOOLS.map(t=>
    `- ${t.name}: ${t.purpose}. Когда: ${t.when}.\n  Аргументы: ${Object.entries(t.args).map(([k,v])=>`${k} — ${v}`).join("; ")}`
  ).join("\n");
}

