// Переписка переживает перезаход: разметка сохраняется в хранилище и
// возвращается на экран. Обработчики при этом НЕ сохраняются, и всё, что
// помнит о живом поведении через разметку, после восстановления врёт.
import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";

const SRC=readFileSync(new URL("../public/index.html",import.meta.url),"utf8");
const fn=(name)=>{
  const at=SRC.indexOf(`function ${name}(`);
  assert.notEqual(at,-1,`функции ${name} нет`);
  return SRC.slice(at,SRC.indexOf("\nfunction ",at+1));
};

test("подключение кнопок не помечается в разметке", () => {
  // Жалоба: «не реагирует только на кнопки в приветственном сообщении».
  // bindQuick ставил кнопке data-bound="1", чтобы не навешивать обработчик
  // дважды. Отметка попадала в сохранённую разметку, обработчик — нет.
  // При следующем заходе кнопки возвращались с отметкой и без обработчика,
  // и проверка считала их уже подключёнными. Карточки работали: у них такой
  // отметки не было, — поэтому мёртвыми выглядели ровно кнопки-подсказки.
  const body=fn("bindQuick");
  assert.ok(!/dataset\.bound/.test(body),"признак подключения в разметке не переживёт восстановление");
  assert.match(body,/onclick=/,"обработчик должен назначаться безусловно");
});

test("ни одна привязка не держит состояние в разметке", () => {
  // Правило, а не частный случай: присваивание onclick и так заменяет
  // прежний обработчик, поэтому отметки «уже подключено» не нужны нигде,
  // а пережить сохранение они могут все.
  for(const name of ["bindQuick","bindCards","bindPlanCard"]){
    const body=fn(name);
    assert.ok(!/dataset\.(bound|wired|ready|init)/.test(body),
      `${name}: отметка подключения в разметке — ловушка, она переживёт сохранение, а обработчик нет`);
  }
});

test("восстановление заново подключает кнопки-подсказки", () => {
  const body=fn("restoreChat");
  assert.match(body,/bindQuick\(\)/,"иначе восстановленные подсказки останутся без обработчиков");
  assert.match(body,/bindCards\(/);
  // Снимаем исполняемое: хранилище правит кто угодно с доступом к origin.
  assert.match(body,/script,iframe,object,embed/);
  assert.match(body,/\^on/,"атрибуты-обработчики из хранилища не возвращаем на экран");
});

test("кнопка-подсказка несёт свой текст в разметке", () => {
  // Текст обязан быть в data-quick: после восстановления взять его больше
  // неоткуда — состояния той реплики уже нет.
  const body=fn("quick");
  assert.match(body,/data-quick="\$\{esc\(x\)\}"/,"текст подсказки должен переживать сохранение");
});
